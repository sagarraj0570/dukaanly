import uuid
from fastapi import APIRouter, Depends, status, Request, Header
from sqlalchemy.ext.asyncio import AsyncSession

from app.db.session import get_db
from app.models.user import User, UserRole
from app.schemas.payment import PaymentInitiationResponse, PaymentVerificationRequest, PaymentResponse
from app.services import payment as payment_service
from app.api.dependencies import require_role

router = APIRouter()

@router.post("/orders/{order_id}/payment", response_model=PaymentInitiationResponse)
async def initiate_payment(
    order_id: uuid.UUID,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(require_role(UserRole.customer))
):
    """
    Initiate a payment for an order.
    Returns the provider order details to be used by the frontend SDK.
    """
    return await payment_service.initiate_payment(db=db, order_id=order_id, customer=current_user)

@router.post("/payments/verify", response_model=PaymentResponse)
async def verify_payment(
    request: PaymentVerificationRequest,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(require_role(UserRole.customer))
):
    """
    Verify a payment cryptographic signature generated by the client SDK.
    """
    return await payment_service.verify_payment(db=db, verification_data=request, customer=current_user)

@router.post("/payments/webhook")
async def provider_webhook(
    request: Request,
    x_razorpay_signature: str = Header(..., description="Razorpay Webhook Signature"),
    db: AsyncSession = Depends(get_db)
):
    """
    Handle webhooks from the payment provider (e.g. Razorpay).
    """
    payload_bytes = await request.body()
    return await payment_service.process_webhook(db=db, payload=payload_bytes, signature=x_razorpay_signature)
